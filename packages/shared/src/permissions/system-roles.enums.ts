import { PERMISSIONS, type PermissionKey } from './permissions.catalog.js';

/**
 * Layer 2 of the permission model: what each system role starts with.
 *
 * Transcribed from `docs/security/permission-model.md` §4, which stays the source of truth for the
 * *matrix*; `test/permissions/system-roles-match-model.test.ts` parses those tables and fails on any
 * difference, in either direction. A role is a **starting point**, not a straitjacket: what one
 * person needs beyond it is expressed by a per-user override (layer 3) or a resource ACL (layer 4),
 * never by inventing a fortieth role.
 *
 * Two properties of this table are decisions rather than data, and both are asserted:
 *
 *   * **`owner` holds every key.** Ownership is not a large role — it is the absence of a ceiling,
 *     and the permission layer says so by construction rather than by a special case at each call.
 *   * **Separation of duties between `admin` and `manager`.** The person who hands out access does
 *     not see money — no cost rates, no margin, no invoices, no timesheet approval; the person who
 *     runs delivery does not administer the installation — no settings, no roles, no integrations.
 *     Collapsing the two is the most common way a small team ends up with one omnipotent account.
 *
 * Only ALLOW lives here. A role that could deny would make «which role wins» unanswerable the moment
 * a person holds two of them — the classic RBAC trap this model avoids by construction (a DENY is a
 * per-user override, layer 3).
 */

