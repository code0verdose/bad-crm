/** Ownership is the absence of a ceiling; this is where that is written down once. */
export const isOwnerRole = (role: SystemRoleKey): boolean => role === 'owner';

/** Every key of the catalogue that no system role grants — useful in review, empty today. */
export const permissionsGrantedByNoRole = (): readonly PermissionKey[] => {
  const granted = new Set<PermissionKey>(
    SYSTEM_ROLE_KEYS.flatMap((role) => [...SYSTEM_ROLE_PERMISSIONS[role]]),
  );

  return PERMISSIONS.filter((key) => !granted.has(key));
};
